import path from "node:path";
import { fileURLToPath } from "node:url";
import { mkdir, writeFile } from "node:fs/promises";
import * as esbuild from "esbuild";

const scriptDir = path.dirname(fileURLToPath(import.meta.url));
const rootDir = path.resolve(scriptDir, "..");

function parseOutputDir(argv) {
  if (argv.length === 0) {
    return path.join(rootDir, "dist", "frontend");
  }
  if (argv.length === 2 && argv[0] === "--outdir" && argv[1]) {
    return path.resolve(process.cwd(), argv[1]);
  }
  throw new Error("Usage: node scripts/build-frontend.mjs [--outdir <directory>]");
}

const outputDir = parseOutputDir(process.argv.slice(2));
const bundlePath = path.join(outputDir, "code.bundle.js");
const metadataPath = path.join(outputDir, "code.bundle.meta.json");

await mkdir(outputDir, { recursive: true });

const result = await esbuild.build({
  absWorkingDir: rootDir,
  entryPoints: ["src/frontend-entry.js"],
  outfile: bundlePath,
  bundle: true,
  platform: "browser",
  format: "iife",
  target: ["es2020"],
  charset: "utf8",
  keepNames: true,
  treeShaking: false,
  minify: false,
  sourcemap: "external",
  sourcesContent: true,
  legalComments: "none",
  metafile: true,
  logLevel: "silent",
  banner: {
    js: "/* Generated by scripts/build-frontend.mjs. Do not edit directly. */",
  },
});

await writeFile(metadataPath, `${JSON.stringify(result.metafile, null, 2)}\n`, "utf8");

const relativeBundle = path.relative(rootDir, bundlePath) || bundlePath;
process.stdout.write(`Frontend bundle written: ${relativeBundle}\n`);
